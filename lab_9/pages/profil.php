<h2 style="color:#2c3e50; margin-top:0;">Profil Perguruan Tinggi</h2>
<p>Kampus Nusantara didirikan pada tahun 2010 dengan komitmen tinggi dalam mencetak lulusan profesional di bidang teknologi informasi, rekayasa perangkat lunak, dan sistem cerdas.</p>
<ul>
  <li><strong>Visi:</strong> Menjadi perguruan tinggi unggul berbasis riset teknologi global.</li>
  <li><strong>Misi:</strong> Menyelenggarakan pendidikan berkualitas tinggi dan inovatif.</li>
</ul>